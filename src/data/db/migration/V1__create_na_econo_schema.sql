-- Description: Create initial schema for "Nueva Acrópolis - San Salvador"
-- Target DB  : PostgreSQL 12+
-- Source     : database-er.dbml (v4)
--
-- Notes:
--   * Each table has an internal surrogate PK `id` (BIGINT IDENTITY).
--     It is not exposed through JSON contracts/CSV; business keys (id_*)
--     remain UNIQUE and are the ones referenced by the current API.
--   * `timestamp` columns use `timestamp without time zone` to match the
--     DBML definition. Change to `timestamptz` if the backend stores UTC.
--   * UNIQUE constraints already create their own indexes, so redundant
--     explicit indexes on those columns (e.g. miembros.dui) are omitted.
-- ============================================================================

-- ============================================================================
-- 1. Catálogos
-- ============================================================================

CREATE TABLE catalogo_estatus (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    codigo         varchar(2)  NOT NULL,
    nombre         varchar(150) NOT NULL,
    es_activo      boolean     NOT NULL,
    color_familia  varchar(50),

    CONSTRAINT pk_catalogo_estatus PRIMARY KEY (id),
    CONSTRAINT uq_catalogo_estatus_codigo UNIQUE (codigo),
    CONSTRAINT uq_catalogo_estatus_nombre UNIQUE (nombre),
    CONSTRAINT ck_catalogo_estatus_codigo CHECK (codigo ~ '^[0-9]{2}$'),
    CONSTRAINT ck_catalogo_estatus_activo CHECK (es_activo = (codigo NOT LIKE '9%'))
);

CREATE TABLE horarios (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    id_horario   integer    NOT NULL,
    dia          varchar(10) NOT NULL,
    hora_inicio  time       NOT NULL,
    hora_fin     time       NOT NULL,

    CONSTRAINT pk_horarios PRIMARY KEY (id),
    CONSTRAINT uq_horarios_id_horario UNIQUE (id_horario),
    CONSTRAINT ck_horarios_dia CHECK (
        dia IN ('Lunes', 'Martes', 'Miércoles', 'Jueves', 'Viernes', 'Sábado')
    ),
    CONSTRAINT ck_horarios_rango CHECK (hora_inicio < hora_fin)
);

CREATE TABLE instructores (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    id_instructor    integer      NOT NULL,
    nombre_completo  varchar(150) NOT NULL,
    id_estatus       varchar(2)   NOT NULL,
    estatus          varchar(150) NOT NULL,

    CONSTRAINT pk_instructores PRIMARY KEY (id),
    CONSTRAINT uq_instructores_id_instructor UNIQUE (id_instructor)
);

CREATE TABLE grupos (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    id_grupo       integer      NOT NULL,
    numero_grupo   varchar(150) NOT NULL,
    id_horario     integer      NOT NULL,
    id_instructor  integer      NOT NULL,

    CONSTRAINT pk_grupos PRIMARY KEY (id),
    CONSTRAINT uq_grupos_id_grupo UNIQUE (id_grupo)
);

