CREATE TABLE miembros (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY,
    id_miembro         integer      NOT NULL,
    miembro_aspirante  varchar(150) NOT NULL,
    id_estatus         varchar(2)   NOT NULL,
    estatus            varchar(100) NOT NULL,
    dui                varchar(10)  NOT NULL,
    celular            varchar(20)  NOT NULL,
    correo             varchar(255) NOT NULL,
    grupo_horario      varchar(150),
    instructores       varchar(250),
    concepto_pago      varchar(150),
    cuota              numeric(10,2) NOT NULL,
    fecha_ingreso      date,
    condicion          varchar(30),
    id_grupo           integer,
    id_instructor      integer,

    CONSTRAINT pk_miembros PRIMARY KEY (id),
    CONSTRAINT uq_miembros_id_miembro UNIQUE (id_miembro),
    CONSTRAINT uq_miembros_dui UNIQUE (dui),
    CONSTRAINT ck_miembros_dui CHECK (dui ~ '^[0-9]{8}-[0-9]$'),
    CONSTRAINT ck_miembros_cuota CHECK (cuota > 0)
);

CREATE TABLE cuotas_membresia (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    id_registro    integer      NOT NULL,
    miembro_id     integer      NOT NULL,
    dui            varchar(10),
    grupo_horario  varchar(150) NOT NULL,
    mes_pagado     varchar(30)  NOT NULL,
    monto_cuota    numeric(10,2) NOT NULL,
    fecha_pago     date         NOT NULL,
    metodo_pago    varchar(50)  NOT NULL,
    referencia     varchar(100),

    CONSTRAINT pk_cuotas_membresia PRIMARY KEY (id),
    CONSTRAINT uq_cuotas_membresia_id_registro UNIQUE (id_registro),
    CONSTRAINT ck_cuotas_membresia_dui CHECK (
        dui IS NULL OR dui ~ '^[0-9]{8}-[0-9]$'
    ),
    CONSTRAINT ck_cuotas_membresia_monto CHECK (monto_cuota > 0),
    CONSTRAINT ck_cuotas_membresia_mes CHECK (
        mes_pagado IN (
            '01-ENERO', '02-FEBRERO', '03-MARZO', '04-ABRIL',
            '05-MAYO', '06-JUNIO', '07-JULIO', '08-AGOSTO',
            '09-SEPTIEMBRE', '10-OCTUBRE', '11-NOVIEMBRE', '12-DICIEMBRE',
            'Enero', 'Febrero', 'Marzo', 'Abril', 'Mayo', 'Junio',
            'Julio', 'Agosto', 'Septiembre', 'Octubre', 'Noviembre', 'Diciembre'
        )
    )
);

CREATE TABLE materiales_clase (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    id_material_log   integer      NOT NULL,
    miembro_id        integer      NOT NULL,
    materia_articulo  varchar(200) NOT NULL,
    monto             numeric(10,2) NOT NULL,
    fecha_solicitud   date         NOT NULL,
    estado_pago       varchar(30)  NOT NULL,
    estado_entrega    varchar(30)  NOT NULL,

    CONSTRAINT pk_materiales_clase PRIMARY KEY (id),
    CONSTRAINT uq_materiales_clase_id_material_log UNIQUE (id_material_log),
    CONSTRAINT ck_materiales_clase_monto CHECK (monto >= 0),
    CONSTRAINT ck_materiales_clase_estado_pago CHECK (
        estado_pago IN ('Pagado', 'Pendiente')
    ),
    CONSTRAINT ck_materiales_clase_estado_entrega CHECK (
        estado_entrega IN ('Entregado', 'En Tránsito', 'Pendiente')
    )
);

CREATE TABLE transacciones_otros (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    id_transaccion    integer      NOT NULL,
    fecha             date         NOT NULL,
    concepto          varchar(250) NOT NULL,
    monto             numeric(12,2) NOT NULL,
    contacto          varchar(150),
    estado            varchar(30)  NOT NULL,
    accion_pendiente  varchar(250),
    archivos_json     text,

    CONSTRAINT pk_transacciones_otros PRIMARY KEY (id),
    CONSTRAINT uq_transacciones_otros_id_transaccion UNIQUE (id_transaccion),
    CONSTRAINT ck_transacciones_otros_estado CHECK (
        estado IN ('Completado', 'Pendiente', 'Anulado')
    )
);

CREATE TABLE archivos_adjuntos (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    uuid            varchar(36) NOT NULL,
    transaccion_id  integer     NOT NULL,
    nombre          varchar(255) NOT NULL,
    tamano          bigint      NOT NULL,
    tipo            varchar(100) NOT NULL,
    data_url        text,
    fecha_subida    timestamp   NOT NULL,

    CONSTRAINT pk_archivos_adjuntos PRIMARY KEY (id),
    CONSTRAINT uq_archivos_adjuntos_uuid UNIQUE (uuid),
    CONSTRAINT ck_archivos_adjuntos_tamano CHECK (tamano >= 0)
);

CREATE TABLE reporte_mora (
    id                bigint GENERATED BY DEFAULT AS IDENTITY,
    id_mora           integer      NOT NULL,
    miembro_id        integer      NOT NULL,
    saldo_anterior    numeric(10,2) DEFAULT 0,
    saldo_actual      numeric(10,2) NOT NULL,
    meses_en_mora     integer      NOT NULL,
    detalle_meses     text         NOT NULL,
    ultimo_contacto   date,
    estado_gestion    varchar(50)  NOT NULL,

    CONSTRAINT pk_reporte_mora PRIMARY KEY (id),
    CONSTRAINT uq_reporte_mora_id_mora UNIQUE (id_mora),
    CONSTRAINT ck_reporte_mora_saldo_anterior CHECK (saldo_anterior >= 0),
    CONSTRAINT ck_reporte_mora_saldo_actual CHECK (saldo_actual >= 0),
    CONSTRAINT ck_reporte_mora_meses CHECK (meses_en_mora >= 1),
    CONSTRAINT ck_reporte_mora_estado_gestion CHECK (
        estado_gestion IN ('Notificado', 'En Negociación', 'Sin Respuesta')
    )
);

